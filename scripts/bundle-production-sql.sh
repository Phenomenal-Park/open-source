#!/usr/bin/env bash
# Concatenate all migrations into one file for the Supabase SQL editor (first-time setup).
# Never includes local-shim.sql or the dev seeds.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/supabase/production-setup.sql"
{
  echo "-- Myeongdong Street Map: first-time production database setup."
  echo "-- Generated by scripts/bundle-production-sql.sh from supabase/migrations — do not edit by hand."
  echo "-- Paste into Supabase → SQL Editor → Run, ONCE, on a NEW empty project."
  for f in "$ROOT"/supabase/migrations/*.sql; do echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; done
} > "$OUT"
echo "wrote $OUT"
